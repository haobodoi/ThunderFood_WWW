"""Build a standalone SQL install from the maintained schema, migration and demo seed.
No database connection, deletion, or external dependencies. Run from any directory.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def build():
    base = (ROOT / 'thunderfood_mariadb_v4.sql').read_text(encoding='utf-8')
    # A fresh install deliberately fails on the first statement if the DB exists.
    # There is no DROP DATABASE and no need to source other SQL files.
    base = base[base.index('CREATE DATABASE thunderfood'):]
    header = '''-- THUNDERFOOD FINAL — standalone fresh/demo installation (MariaDB 10.6+).
-- Includes schema v4 + admin V5 + 1,000 customers / 20,000 historical demo orders.
-- Generated by: python backend/database/build_final_sql.py
-- All demo login passwords: 123456. Do not use these accounts in production.
-- NO DROP DATABASE. If thunderfood already exists, CREATE DATABASE fails.
-- Use a fresh database/server; stop on the first SQL error. Never use --force.
-- Existing installations: apply migrations/V5__admin.sql instead of this installer.
-- Records are dated relative to import time, covering the last two years.

'''
    migration = (ROOT / 'migrations/V5__admin.sql').read_text(encoding='utf-8')
    seed = (ROOT / 'seeds/statistics_demo.sql').read_text(encoding='utf-8')
    base = base.replace('SET NAMES utf8mb4;', "SET NAMES utf8mb4;\nSET time_zone = '+07:00';", 1)
    result = header + base + '\n-- FINAL ADMIN SCHEMA\n' + migration + '\n-- LARGE DEMO DATASET\n' + seed
    target = ROOT / 'thunderfood_final.sql'
    target.write_text(result, encoding='utf-8', newline='\n')
    print(f'Built {target.name}: {len(result.encode("utf-8")):,} bytes')


if __name__ == '__main__':
    build()
